def get_scenario(task_id: str) -> list[dict[str, str]]:
    """根据任务 ID 返回情景对话，未命中时使用默认对话。"""
    return SCENARIOS.get(task_id, DEFAULT_SCENARIO)


def scenario_title(fraud_type: str) -> str:
    """根据诈骗类型生成情景标题。"""
    return f"{fraud_type} · 模拟情景对话"


def scenario_response(task_id: str, fraud_type: str) -> dict[str, Any]:
    """构造训练任务详情接口返回的 scenario 字段。"""
    return {
        "title": scenario_title(fraud_type),
        "messages": get_scenario(task_id),
    }
